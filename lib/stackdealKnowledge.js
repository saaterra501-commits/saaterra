/**
 * Fast keyword-based FAQ matcher for immediate (< 20ms) responses
 */
export function matchFaqQuery(query) {
  if (!query || typeof query !== 'string') return null;
  const qLower = query.toLowerCase().trim();

  // If user is explicitly asking for software tools or recommendations, let the deal recommender handle it
  if (/\b(tool|tools|software|recommend|suggest|chahiye|khareedna)\b/i.test(qLower)) {
    return null;
  }

  // Score each FAQ by matched keywords
  let bestMatch = null;
  let highestScore = 0;

  for (const item of STACKDEAL_FAQS) {
    let score = 0;
    for (const kw of item.keywords) {
      if (qLower === kw) {
        score += 15;
      } else if (qLower.includes(kw)) {
        score += kw.length > 4 ? 8 : 4;
      }
    }
    if (score > highestScore && score >= 4) {
      highestScore = score;
      bestMatch = item;
    }
  }

  return bestMatch ? bestMatch.answer : null;
}
